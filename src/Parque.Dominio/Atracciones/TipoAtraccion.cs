namespace Parque.Dominio.Atracciones;

/// <summary>
/// Representa los diferentes tipos de atracciones disponibles en el parque.
/// </summary>
public enum TipoAtraccion
{
    /// <summary>
    /// Atracción de montaña rusa con recorridos emocionantes.
    /// </summary>
    MontañaRusa,

    /// <summary>
    /// Atracción simulada con tecnología avanzada.
    /// </summary>
    Simulador,

    /// <summary>
    /// Espectáculo en vivo con actores y efectos especiales.
    /// </summary>
    Espectaculo,

    /// <summary>
    /// Zona interactiva con actividades participativas.
    /// </summary>
    ZonaInteractiva
}
